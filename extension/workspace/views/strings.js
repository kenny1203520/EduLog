/** Bind a keyed string to an element (text, or an attribute when `attr` is set). */
export function say(node, key, params = {}, attr) {
  const ui = globalThis.edulogUi
  if (ui) { ui.text(node, key, params, attr); return node }
  const values = typeof params === 'function' ? params() : params
  const value = (strings[key]?.[0] ?? key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '')
  if (attr) node.setAttribute(attr, value); else node.textContent = value
  return node
}
/** Translate a key now (for composed strings). */
export function tr(key, params = {}) {
  const ui = globalThis.edulogUi
  if (ui) return ui.t(key, params)
  return (strings[key]?.[0] ?? key).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '')
}
